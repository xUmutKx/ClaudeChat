def paint(ops):
    g = [['.'] * 20 for _ in range(18)]
    for x, y, w, h, c in ops:
        for yy in range(max(0, y), min(18, y + h)):
            for xx in range(max(0, x), min(20, x + w)):
                g[yy][xx] = c
    rows = [''.join(r) for r in g]
    assert len(rows) == 18 and all(len(r) == 20 for r in rows)
    assert all(c in PAL for r in rows for c in r) and all(c != '.' for r in rows for c in r)
    return rows

if __name__ == '__main__':
    assert len(ROOMS) == 30, len(ROOMS)
    for n, ops in ROOMS.items():
        rows = paint(ops)
        open(os.path.join(RES, f'room_{n}.xml'), 'w').write(hat_xml(PAL, rows))
    print(len(ROOMS), 'rooms')
